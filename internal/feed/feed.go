// Package feed описывает источник рыночных данных.
package feed

import (
	"context"

	"github.com/IronGigas/market-data-pipeline/internal/domain"
)

// Feed — источник потока сделок.
//
// Интерфейс введён при единственной реализации сознательно: он фиксирует
// границу между «откуда берутся сделки» и «что с ними делать дальше».
// Сервис ingestor зависит от интерфейса и не знает про WebSocket, реконнекты
// и формат сообщений Binance.
type Feed interface {
	// Run блокируется до отмены ctx или неустранимой ошибки и передаёт
	// каждую полученную сделку в handler.
	//
	// handler вызывается последовательно, из одной горутины: реализации не
	// нужно заботиться о синхронизации, но и блокироваться в нём нельзя —
	// пауза в handler останавливает чтение из сокета и копит отставание
	// от рынка. Ошибка из handler считается неустранимой: Run прекращает
	// работу и возвращает её, не пытаясь переподключиться.
	//
	// Отмена ctx — штатная остановка: Run возвращает nil, а не ошибку.
	Run(ctx context.Context, handler func(domain.Trade) error) error
}
